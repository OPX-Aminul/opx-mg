#!/usr/bin/env sh
# One-shot installer. Run inside Termux:
#   curl -fsSL https://raw.githubusercontent.com/OPX-Aminul/opx-mg/main/install.sh | sh
set -eu

REPO="${OPX_MG_REPO:-OPX-Aminul/opx-mg}"
BRANCH="${OPX_MG_BRANCH:-main}"
PREFIX="${PREFIX:-}"
API="https://api.github.com/repos/${REPO}/releases/latest"

if [ -z "$PREFIX" ] || [ ! -d "$PREFIX" ]; then
    echo "This installer is meant to run inside Termux (\$PREFIX is unset)." >&2
    echo "Clone instead: git clone https://github.com/${REPO}.git && ./bin/opx-mg setup" >&2
    exit 1
fi

DEST="${PREFIX}/lib/opx-mg"
BIN="${PREFIX}/bin/opx-mg"
TMP="${PREFIX}/tmp/opx-mg-install"
LOGDIR="${OPX_MG_HOME:-$PREFIX/var/lib/opx-mg}/logs"
LOG="$LOGDIR/opx-mg.log"
mkdir -p "$DEST" "${PREFIX}/bin" "$TMP" "$LOGDIR"
log() { printf '%s [INSTALL] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" | tee -a "$LOG" >&2; }
log "installer start: repo=$REPO branch=$BRANCH dest=$DEST"

detect_arch() {
    case "$(uname -m 2>/dev/null || echo unknown)" in
        aarch64|arm64)                   printf '%s' aarch64 ;;
        armv7l|armv8l|armv7a|armv8a|arm) printf '%s' armv7a ;;
        x86_64|amd64)                    printf '%s' x86_64 ;;
        i?86)                            printf '%s' i686 ;;
        *)                               printf '%s' unknown ;;
    esac
}

ARCH=$(detect_arch)
log "host arch: $ARCH"
case "$ARCH" in
    aarch64|armv7a) ;;
    *) echo "opx-mg: warning: unsupported host arch '$ARCH' (releases ship aarch64 and armv7a)" >&2 ;;
esac

download() {
    url=$1 dest=$2
    if command -v curl >/dev/null 2>&1; then
        curl -fL --retry 3 -o "$dest" "$url"
    else
        wget -O "$dest" "$url"
    fi
}

echo "opx-mg: installing into $DEST (host arch $ARCH)"

installed=0
if download "$API" "$TMP/latest.json"; then
    tag=""
    if command -v python3 >/dev/null 2>&1; then
        tag=$(python3 - "$TMP/latest.json" <<'PY'
import json,sys
print((json.load(open(sys.argv[1])).get("tag_name") or "").lstrip("v"))
PY
)
    fi
    if [ -n "$tag" ]; then
        echo "opx-mg: latest release v${tag}"
        tarball_url=""
        if command -v python3 >/dev/null 2>&1; then
            tarball_url=$(python3 - "$TMP/latest.json" "opx-mg-${tag}.tar.gz" <<'PY'
import json,sys
name=sys.argv[2]
d=json.load(open(sys.argv[1]))
for a in d.get("assets") or []:
    if a.get("name")==name:
        print(a.get("browser_download_url") or "")
        sys.exit(0)
sys.exit(1)
PY
) || true
        fi
        if [ -n "$tarball_url" ]; then
            log "using release tarball v${tag}"
            archive="$TMP/opx-mg-${tag}.tar.gz"
            download "$tarball_url" "$archive"
            tar -xzf "$archive" -C "$DEST"
            installed=1
        fi
    fi
fi

if [ "$installed" -ne 1 ]; then
    log "no release tarball yet, cloning ${BRANCH}"
    echo "opx-mg: no release tarball yet, cloning ${BRANCH}"
    TARBALL="https://codeload.github.com/${REPO}/tar.gz/refs/heads/${BRANCH}"
    archive="$TMP/src.tar.gz"
    download "$TARBALL" "$archive"
    tar -xzf "$archive" -C "$TMP"
    src=$(find "$TMP" -maxdepth 1 -type d -name 'opx-mg-*' | head -n 1)
    if [ -z "$src" ]; then
        echo "unpack failed" >&2
        exit 1
    fi
    cp -R "$src/." "$DEST/"
fi

chmod +x "$DEST/bin/opx-mg" "$DEST/install.sh" 2>/dev/null || true
if [ ! -f "$DEST/bin/opx-mg" ]; then
    echo "opx-mg: install failed: $DEST/bin/opx-mg is missing" >&2
    exit 1
fi
# Termux has no /usr/bin/env, so exec'ing bin/opx-mg (directly or through a
# symlink) fails with "not found" unless the Termux exec wrapper is present.
# The launcher uses the absolute Termux sh path and hands the real CLI to sh.
rm -f "$BIN"
cat > "$BIN" <<EOF
#!${PREFIX}/bin/sh
# opx-mg launcher — generated by install.sh, do not edit.
exec "${PREFIX}/bin/sh" "$DEST/bin/opx-mg" "\$@"
EOF
chmod +x "$BIN"
log "installer linked $BIN; running setup"
echo "opx-mg: linked $BIN"
echo "opx-mg: running setup (Termux packages + QEMU, usbredirect, guest disk)"
"$BIN" setup || true
echo
if [ "$ARCH" = armv7a ]; then
    echo "opx-mg: 32-bit host — QEMU comes from TUR (tur-repo + qemu-system-aarch64-9),"
    echo "        installed by setup above. If pkg refuses, 64-bit Termux is faster:"
    echo "        'getprop ro.product.cpu.abi' = arm64-v8a means the phone supports it."
fi
echo "opx-mg: packages are installed automatically; one step is still manual,"
echo "        because Android will not let a shell install an APK:"
echo "        install the Termux:API APK from the same source as Termux."
echo
echo "Then just run: opx-mg   (VM + USB watcher; plug the adapter, tap OK)"
echo "Update later: opx-mg -u"
